    private void ActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ActualizarActionPerformed
        // TODO add your handling code here:
        try {

            String codigo = Codigo.getText();
            String nombre = Nombre.getText();
            double precioBase = Double.parseDouble(PrecioBase.getText());
            int cantidadDisponible = Integer.parseInt(CantidadDisponible.getText());

            String tipo = (String) TipoProducto.getSelectedItem();

            boolean activo = Estado.getSelectedItem().equals("Activo");

            if (tipo.equals("Producto físico")) {

                double peso = Double.parseDouble(Peso.getText());
                double costoEnvio = Double.parseDouble(CostoEnvio.getText());

                Producto productoActualizado = new ProductoFisico(
                        codigo,
                        nombre,
                        precioBase,
                        cantidadDisponible,
                        peso,
                        costoEnvio
                );

                productoActualizado.setActivo(activo);

                productoController.actualizarProducto(productoActualizado);

            } else {

                double tamañoArchivo
                        = Double.parseDouble(TamañoArchivo.getText());

                String formato = Formato.getText();

                Producto productoActualizado = new ProductoDigital(
                        codigo,
                        nombre,
                        precioBase,
                        cantidadDisponible,
                        tamañoArchivo,
                        formato
                );

                productoActualizado.setActivo(activo);

                productoController.actualizarProducto(productoActualizado);
            }
            
            if (listarProductos != null && listarProductos.isDisplayable()) {
                listarProductos.cargarTabla();
            }

            JOptionPane.showMessageDialog(
                    this,
                    "Producto actualizado correctamente."
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Los campos numéricos deben contener valores válidos.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }


    }//GEN-LAST:event_ActualizarActionPerformed

