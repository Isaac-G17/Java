    private void BuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarActionPerformed
        // TODO add your handling code here:
        try {

            String codigo = Codigo.getText();

            productoActual = productoController.buscarProducto(codigo);

            // Aquí cargaremos los datos
            Codigo.setText(productoActual.getCodigo());
            Nombre.setText(productoActual.getNombre());
            PrecioBase.setText(String.valueOf(productoActual.getPrecioBase()));
            CantidadDisponible.setText(String.valueOf(productoActual.getCantidadDisponible()));

            if (productoActual instanceof ProductoFisico productoFisico) {

                TipoProducto.setSelectedItem("Producto físico");

                Peso.setEnabled(true);
                CostoEnvio.setEnabled(true);

                TamañoArchivo.setEnabled(false);
                Formato.setEnabled(false);

                Peso.setText(String.valueOf(productoFisico.getPeso()));
                CostoEnvio.setText(String.valueOf(productoFisico.getCostoEnvio()));

            } else if (productoActual instanceof ProductoDigital productoDigital) {

                TipoProducto.setSelectedItem("Producto digital");

                Peso.setEnabled(false);
                CostoEnvio.setEnabled(false);

                TamañoArchivo.setEnabled(true);
                Formato.setEnabled(true);

                TamañoArchivo.setText(
                        String.valueOf(productoDigital.getTamañoArchivo())
                );

                Formato.setText(productoDigital.getFormato());
            }

            TipoProducto.setEnabled(false);

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_BuscarActionPerformed

    private void TipoProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_TipoProductoActionPerformed
        String tipo = (String) TipoProducto.getSelectedItem();

        if (tipo.equals("Producto físico")) {

            Peso.setEnabled(true);
            CostoEnvio.setEnabled(true);

            TamañoArchivo.setEnabled(false);
            Formato.setEnabled(false);
            TamañoArchivo.setText("");
            Formato.setText("");

        } else {

            Peso.setEnabled(false);
            CostoEnvio.setEnabled(false);
            Peso.setText("");
            CostoEnvio.setText("");

            TamañoArchivo.setEnabled(true);
            Formato.setEnabled(true);
        }
    }//GEN-LAST:event_TipoProductoActionPerformed

